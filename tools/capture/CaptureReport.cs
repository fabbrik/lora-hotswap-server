using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using LoraHotswap.Compare;

namespace LoraHotswap.Capture;

/// <summary>
/// Renders the captured answers as the Markdown a reader judges: the published document
/// and the generated block inside <c>README.md</c>.
///
/// Nothing is composed here that the model did not produce. Every answer is emitted
/// verbatim inside a fenced block -- never trimmed, never tidied, never shortened, and
/// never replaced by a better one. A disappointing answer is published as it came.
/// </summary>
public static class CaptureReport
{
    /// <summary>The command that regenerates both documents.</summary>
    public const string RegenerateCommand = "dotnet run -c Release --project tools/capture";

    /// <summary>The published capture, relative to the repository root.</summary>
    public const string DefaultOutputPath = "docs/three-tenants.md";

    /// <summary>Opens the generated region of <c>README.md</c>.</summary>
    public const string ReadmeBeginMarker = "<!-- BEGIN GENERATED by tools/capture -- do not edit by hand -->";

    /// <summary>Closes the generated region of <c>README.md</c>.</summary>
    public const string ReadmeEndMarker = "<!-- END GENERATED by tools/capture -->";

    /// <summary>
    /// The share of words two answers must have in common before the document says so. It
    /// exists to stop a reader being left to notice for themselves that a prompt did not
    /// separate the adapters. Below it, the answers are simply published.
    /// </summary>
    public const double CloseAnswerThreshold = 0.7;

    /// <summary>
    /// The shortest answer word overlap is allowed to judge. "I am Alice." and "I am Bob." (two adapters differing in one word)
    /// share four fifths of their words and say two different things -- the one word that
    /// differs is the whole point -- so on a short answer the measure says nothing worth
    /// publishing. Identical short answers are still reported: that check is exact.
    /// </summary>
    public const int ShortestComparableAnswer = 20;

    /// <summary>
    /// The sentence every published capture carries: generation here is one sample, not a
    /// fixed output, so the document never reads as a specification of what the model says.
    /// </summary>
    public const string NonDeterminismNote =
        "**One sample, not a fixed output.** Sampling is greedy, but llama.cpp's CPU kernels are not " +
        "bit-reproducible across thread counts, builds and machines, and the prompt, the adapter scale, the " +
        "context size and the token budget all move the result. Re-running the tool regenerates these answers " +
        "and they may differ. This is one run's output, quoted as it came -- not a guarantee of what the model " +
        "will say next time.";

    /// <summary>
    /// What the difference check can and cannot establish. It compares words, so it reports
    /// answers that are identical or share most of their wording -- and it cannot tell that
    /// two differently worded answers mean the same thing. Published so that the absence of
    /// a note is never read as the document claiming the adapters were separated.
    /// </summary>
    public static string DifferenceCheckNote { get; } =
        "**Whether the answers differ is yours to judge.** The tool compares words: it says so when two tenants " +
        "returned identical text, or text sharing most of its wording, and it is not allowed to judge answers " +
        $"shorter than {ShortestComparableAnswer.ToString(CultureInfo.InvariantCulture)} words, where the one " +
        "word that differs is often the whole point. It cannot tell that two differently worded answers mean the " +
        "same thing. No note above means only that no pair tripped that check -- never that the prompt separated " +
        "the adapters.";

    /// <summary>
    /// What the demonstration deliberately is not. Correctness lives in Story 2.5's identity
    /// proof and Story 1.7's merge verification; this document is neither. The tenant count
    /// comes from the plan, so a run over some other set of tenants does not publish a
    /// sentence contradicting the answers beside it.
    /// </summary>
    public static string NotAProof(CapturePlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);

        return "**This is a demonstration, not a benchmark and not a correctness proof.** It shows that " +
            $"{Count(plan.Tenants.Count, "tenant", "tenants")} in one process answer as themselves. That the " +
            "right adapter served each request is proven by Story 2.5's identity proof and its three sabotages; " +
            "that an adapter's artifact is the one it claims to be is proven by Story 1.7's merge verification. " +
            "What a per-stage cost is, and under which binding strategy, is `docs/strategy-comparison.md`. None " +
            "of those questions is answered by reading the answers here.";
    }

    /// <summary>
    /// How the prompt reaches the model. The server wraps it in the configured template
    /// before tokenizing, so a reader who sends the published prompt text on its own will
    /// not reproduce these answers -- which the documents have to say, beside the prompt.
    /// </summary>
    public static string TemplateNote(CapturePlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);

        return plan.PromptTemplate.Length == 0
            ? "The prompt reaches the model exactly as printed: no template is applied (raw completion)."
            : "**That text is not what the model saw.** The server wraps every prompt in the configured " +
              $"template before tokenizing it -- here {plan.TemplateLine}, with `{{prompt}}` replaced by the " +
              "text above. Sending the bare text to a plain completion API will not reproduce these answers.";
    }

    /// <summary>
    /// What the token budget can do to an answer. The tool never shortens one, but the
    /// server stops generating at the budget and the response carries no stop reason, so
    /// neither document can mark which answers ran to it -- which is said rather than left
    /// under a blanket claim that answers are never shortened.
    /// </summary>
    public static string BudgetNote(CapturePlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);

        return "**The tool shortens nothing; the token budget can.** Every answer is published exactly as the " +
            $"response carried it, but generation stops at {Count(plan.MaxTokens, "token", "tokens")} " +
            "(`Inference:MaxTokens`). An answer that ran to that budget was cut there, and the response carries " +
            "no stop reason, so neither this document nor the tool can mark which ones did. Raise it with " +
            "`--max-tokens` and re-run.";
    }

    /// <summary>Render the published capture document.</summary>
    public static string Render(CapturePlan plan, CaptureResult result, RunEnvironment environment)
    {
        ArgumentNullException.ThrowIfNull(plan);
        ArgumentNullException.ThrowIfNull(result);
        ArgumentNullException.ThrowIfNull(environment);

        if (result.Answers.Count == 0)
        {
            throw new CaptureAbortedException("The capture collected no answers, so it has nothing to publish.");
        }

        var markdown = new StringBuilder();
        markdown.AppendLine("# Three tenants, one model, one process (Story 3.2)");
        markdown.AppendLine();
        markdown.AppendLine(
            "Generated by `tools/capture`. **Do not edit by hand** -- re-running the tool overwrites this file and");
        markdown.AppendLine("the generated block in `README.md`, and changes nothing else:");
        markdown.AppendLine();
        markdown.AppendLine("```");
        markdown.AppendLine(RegenerateCommand);
        markdown.AppendLine("```");
        markdown.AppendLine();
        markdown.AppendLine(
            $"One process. One copy of `{Path.GetFileName(plan.ModelPath)}` in memory, {BaseModelReadsSentence(result)} " +
            $"{Count(plan.Tenants.Count, "tenant", "tenants")}, each mapped to its own LoRA adapter by content " +
            "hash, served one after another through `POST /v1/generate` on the same host.");
        markdown.AppendLine();
        markdown.AppendLine(
            "Every answer below is the model's own output, quoted exactly as the response carried it -- never " +
            "trimmed, tidied or replaced by a better one.");
        markdown.AppendLine();

        for (int p = 0; p < plan.Prompts.Count; p++)
        {
            AppendPrompt(markdown, plan, result, p);
        }

        markdown.AppendLine("## Reading this");
        markdown.AppendLine();
        markdown.AppendLine($"- {NonDeterminismNote}");
        markdown.AppendLine($"- {BudgetNote(plan)}");
        markdown.AppendLine($"- {DifferenceCheckNote}");
        markdown.AppendLine($"- {NotAProof(plan)}");
        markdown.AppendLine(
            "- **The adapter identity is content-derived.** Each `sha256:` above is the SHA-256 of that adapter's " +
            "own `adapter_model.safetensors`. Admission re-derives it from the bytes at startup, so a tenant " +
            "mapped to an identity the files do not produce fails startup rather than answering.");
        markdown.AppendLine(
            "- **The applied set is the runtime's own record.** `appliedAdapters` is what the runtime handed the " +
            "native context, not what the caller asked for; a response carrying an empty set is rejected rather " +
            "than answered from the base model.");
        markdown.AppendLine(
            "- **What the response establishes, and what it does not.** The tenant, the adapter and the applied " +
            "set under each answer are the response's own members, and an answer whose response disagreed with " +
            "any of them aborts the run. Which prompt an answer sits under is not: the response does not echo " +
            "the prompt, so that pairing is the tool's own record of what it sent.");
        markdown.AppendLine();

        AppendTable(markdown, "## What produced these answers", ["Setting", "Value"],
            plan.Describe().Select(row => (IReadOnlyList<string>)[row.Field, row.Value]));

        AppendTable(markdown, "## Environment (NFR3)", ["Field", "Value"],
            environment.Describe()
                .Append((Field: BaseModelReadsField, Value: Count(result.BaseModelReads, "time", "times")))
                .Select(row => (IReadOnlyList<string>)[row.Field, row.Value]));

        markdown.AppendLine("These answers and their timings are machine-specific and mean nothing detached from this block.");
        markdown.AppendLine();

        markdown.AppendLine("## Provenance");
        markdown.AppendLine();
        markdown.AppendLine(
            "Every served response, in the order it was served -- indented here for reading, members and values");
        markdown.AppendLine(
            "unchanged. Every quotation above is the `text` member of one of these.");
        foreach (ServedAnswer answer in result.Answers)
        {
            markdown.AppendLine();
            markdown.AppendLine($"`{answer.Tenant}`, {PromptLabel(answer.PromptIndex)}, `POST {CaptureRunner.GenerateRoute}`:");
            markdown.AppendLine();
            markdown.AppendLine(Fenced(Indent(answer.ResponseBody), "json"));
        }

        return markdown.ToString();
    }

    /// <summary>
    /// Render the block that lives between the markers in <c>README.md</c>: one prompt,
    /// every tenant's answer, and what produced them. This is what a reader who has never
    /// seen the repository meets first, so it has to answer "what does this do" on its own.
    /// </summary>
    public static string RenderReadmeSection(
        CapturePlan plan, CaptureResult result, RunEnvironment environment, string capturePath)
    {
        ArgumentNullException.ThrowIfNull(plan);
        ArgumentNullException.ThrowIfNull(result);
        ArgumentNullException.ThrowIfNull(environment);

        IReadOnlyList<ServedAnswer> answers = result.Answers.Where(a => a.PromptIndex == 0).ToArray();
        if (answers.Count == 0)
        {
            throw new CaptureAbortedException("The capture collected no answers for its first prompt.");
        }

        var markdown = new StringBuilder();
        markdown.AppendLine(ReadmeBeginMarker);
        markdown.AppendLine();
        markdown.AppendLine("## What this does");
        markdown.AppendLine();
        markdown.AppendLine(
            $"One process. One copy of `{Path.GetFileName(plan.ModelPath)}` in memory, {BaseModelReadsSentence(result)} " +
            $"{Count(plan.Tenants.Count, "tenant", "tenants")}, each with its own LoRA adapter. One prompt, sent " +
            "to all of them:");
        markdown.AppendLine();
        markdown.AppendLine(Quote(plan.Prompts[0].Text));
        markdown.AppendLine();
        markdown.AppendLine(TemplateNote(plan));
        markdown.AppendLine();
        markdown.AppendLine("The answers, exactly as the server returned them:");
        markdown.AppendLine();

        foreach (ServedAnswer answer in answers)
        {
            markdown.AppendLine(
                $"**`{answer.Tenant}`** -- served by `{answer.DirectoryName}` (`{Short(answer.AdapterId)}`):");
            markdown.AppendLine();
            markdown.AppendLine(Quote(answer.Text));
            markdown.AppendLine();
        }

        AppendAnswerDifferenceNote(markdown, answers);

        markdown.AppendLine(
            "No text above was written by hand. `tools/capture` served the one prompt to each tenant in turn on " +
            $"one host, and quoted the `text` member of each response. The full capture -- {CaptureContents(plan)} " +
            $"-- is [`{capturePath}`]({capturePath}), regenerated with `{RegenerateCommand}`.");
        markdown.AppendLine();
        markdown.AppendLine(
            $"Produced on {environment.Machine}, {environment.OperatingSystem}, through " +
            $"{environment.InferenceRuntime}");
        markdown.AppendLine();
        markdown.AppendLine(NonDeterminismNote);
        markdown.AppendLine();
        markdown.AppendLine(BudgetNote(plan));
        markdown.AppendLine();
        markdown.AppendLine(DifferenceCheckNote);
        markdown.AppendLine();
        markdown.AppendLine(NotAProof(plan));
        markdown.AppendLine();
        markdown.Append(ReadmeEndMarker);

        return markdown.ToString();
    }

    /// <summary>
    /// Replace the generated region of <paramref name="readme"/> with
    /// <paramref name="section"/>, leaving every other byte of the file alone.
    /// </summary>
    public static string ReplaceReadmeSection(string readme, string section)
    {
        ArgumentNullException.ThrowIfNull(readme);
        ArgumentNullException.ThrowIfNull(section);

        int begin = readme.IndexOf(ReadmeBeginMarker, StringComparison.Ordinal);
        int end = readme.IndexOf(ReadmeEndMarker, StringComparison.Ordinal);
        if (begin < 0 || end < begin)
        {
            throw new CaptureAbortedException(
                $"README.md has no generated region to replace. It must contain the line '{ReadmeBeginMarker}' " +
                $"followed by '{ReadmeEndMarker}'; the capture never guesses where the demonstration belongs.");
        }

        return readme[..begin] + section + readme[(end + ReadmeEndMarker.Length)..];
    }

    /// <summary>
    /// One answer as a fenced block, verbatim. The fence is long enough to survive an
    /// answer that itself contains backticks, and exactly one newline separates the answer
    /// from the closing fence -- so the published text is recoverable character for
    /// character, which is what "quoted as served" has to mean.
    /// </summary>
    public static string Quote(string text) => Fenced(text, "text");

    /// <summary>
    /// Any block whose content the tool did not write, fenced so the content cannot close
    /// it early. A served answer routinely contains a fence of its own -- and so, then,
    /// does the response body printed to corroborate it -- so the fence is measured against
    /// the content rather than assumed to be three backticks.
    /// </summary>
    public static string Fenced(string content, string info)
    {
        ArgumentNullException.ThrowIfNull(content);
        ArgumentNullException.ThrowIfNull(info);

        int longest = 0, run = 0;
        foreach (char c in content)
        {
            run = c == '`' ? run + 1 : 0;
            longest = Math.Max(longest, run);
        }

        string fence = new('`', Math.Max(3, longest + 1));
        return fence + info + "\n" + content + "\n" + fence;
    }

    /// <summary>The inverse of <see cref="Quote"/>: the answer a fenced block carries.</summary>
    public static string Unquote(string block)
    {
        ArgumentNullException.ThrowIfNull(block);

        int open = block.IndexOf('\n');
        int close = block.LastIndexOf('\n');
        return open < 0 || close <= open ? string.Empty : block[(open + 1)..close];
    }

    /// <summary>An identity shortened for a caption. The whole value is in the published capture.</summary>
    public static string Short(string adapterId)
    {
        ArgumentNullException.ThrowIfNull(adapterId);
        return adapterId.Length <= 15 ? adapterId : adapterId[..15] + "...";
    }

    /// <summary>The environment row naming how often the weights were read.</summary>
    public const string BaseModelReadsField = "Base model reads from disk (this process, during the run)";

    /// <summary>
    /// How often this process read the weights, said as the counter actually measures it:
    /// a delta taken across the run, not a claim about the file's whole lifetime.
    /// </summary>
    public static string BaseModelReadsSentence(CaptureResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        return $"read off disk {Count(result.BaseModelReads, "time", "times")} by this process between the host " +
            "being composed and the last answer.";
    }

    /// <summary>
    /// The share of words two answers have in common, over the union of their words. A
    /// crude measure on purpose: it decides only whether the document says the two answers
    /// are close, never what is published.
    /// </summary>
    public static double Overlap(string first, string second)
    {
        ArgumentNullException.ThrowIfNull(first);
        ArgumentNullException.ThrowIfNull(second);

        HashSet<string> a = Words(first);
        HashSet<string> b = Words(second);
        if (a.Count == 0 || b.Count == 0)
        {
            return a.Count == b.Count ? 1 : 0;
        }

        double shared = a.Intersect(b, StringComparer.Ordinal).Count();
        return shared / a.Union(b, StringComparer.Ordinal).Count();
    }

    /// <summary>Whether an answer is long enough for word overlap to mean anything. </summary>
    public static bool ComparableByWords(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return Words(text).Count >= ShortestComparableAnswer;
    }

    private static HashSet<string> Words(string text) =>
        text.ToLowerInvariant()
            .Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(word => word.Trim('.', ',', ';', ':', '!', '?', '"', '\'', '(', ')', '`'))
            .Where(word => word.Length > 0)
            .ToHashSet(StringComparer.Ordinal);

    /// <summary>What the full capture holds, beyond the one prompt the README shows.</summary>
    private static string CaptureContents(CapturePlan plan)
    {
        int more = plan.Prompts.Count - 1;
        string extra = more > 0 ? $"{Count(more, "further prompt", "further prompts")}, " : string.Empty;
        return extra + "every raw response, and the hardware that produced them";
    }

    private static string PromptLabel(int index) =>
        $"prompt {(index + 1).ToString(CultureInfo.InvariantCulture)}";

    private static void AppendPrompt(StringBuilder markdown, CapturePlan plan, CaptureResult result, int index)
    {
        CapturePrompt prompt = plan.Prompts[index];
        IReadOnlyList<ServedAnswer> answers = result.Answers.Where(a => a.PromptIndex == index).ToArray();

        markdown.AppendLine($"## {prompt.Title}");
        markdown.AppendLine();
        markdown.AppendLine($"*Why this prompt:* {prompt.Why}");
        markdown.AppendLine();
        markdown.AppendLine("The prompt, identical for every tenant:");
        markdown.AppendLine();
        markdown.AppendLine(Quote(prompt.Text));
        markdown.AppendLine();
        markdown.AppendLine(TemplateNote(plan));
        markdown.AppendLine();

        foreach (ServedAnswer answer in answers)
        {
            markdown.AppendLine($"### `{answer.Tenant}` -- `{answer.DirectoryName}`");
            markdown.AppendLine();
            markdown.AppendLine(
                $"Served by `{answer.AdapterId}`, the only adapter the runtime reported applied, under " +
                $"`{answer.BindingStrategy}`, in {Milliseconds(answer.GenerationMicroseconds)} of generation, " +
                $"within a budget of {Count(plan.MaxTokens, "token", "tokens")}.");
            markdown.AppendLine();
            markdown.AppendLine(Quote(answer.Text));
            markdown.AppendLine();
        }

        AppendAnswerDifferenceNote(markdown, answers);
    }

    /// <summary>
    /// Two tenants that answered identically, or nearly so, are said so here, in the
    /// document. The capture claims a difference only where there is one to read, and
    /// "nearly the same" is exactly the case a reader would otherwise have to spot for
    /// themselves by comparing two paragraphs word by word.
    /// </summary>
    private static void AppendAnswerDifferenceNote(StringBuilder markdown, IReadOnlyList<ServedAnswer> answers)
    {
        string[] identical = answers
            .GroupBy(a => a.Text, StringComparer.Ordinal)
            .Where(group => group.Count() > 1)
            .Select(group => string.Join(", ", group.Select(a => $"`{a.Tenant}`")))
            .ToArray();

        // Pairs that are not the same text but say the same thing. Answers already reported
        // as identical are left out, so one collision is never reported twice.
        var close = new List<string>();
        for (int i = 0; i < answers.Count; i++)
        {
            for (int j = i + 1; j < answers.Count; j++)
            {
                if (string.Equals(answers[i].Text, answers[j].Text, StringComparison.Ordinal))
                {
                    continue;
                }

                if (!ComparableByWords(answers[i].Text) || !ComparableByWords(answers[j].Text))
                {
                    continue;
                }

                double overlap = Overlap(answers[i].Text, answers[j].Text);
                if (overlap >= CloseAnswerThreshold)
                {
                    close.Add(
                        $"`{answers[i].Tenant}` and `{answers[j].Tenant}` " +
                        $"({(overlap * 100).ToString("N0", CultureInfo.InvariantCulture)}% of their words in common)");
                }
            }
        }

        if (identical.Length == 0 && close.Count == 0)
        {
            return;
        }

        var note = new StringBuilder("> **These answers are not all different.**");
        if (identical.Length > 0)
        {
            note.Append(" The following tenants returned identical text: ")
                .Append(string.Join("; ", identical))
                .Append('.');
        }

        if (close.Count > 0)
        {
            note.Append(" These pairs are not identical but share most of their wording: ")
                .Append(string.Join("; ", close))
                .Append('.');
        }

        note.Append(
            " Every answer is published as it came. Each was still served by its own adapter -- the responses " +
            "name them -- but this prompt did not make that difference visible.");

        markdown.AppendLine(note.ToString());
        markdown.AppendLine();
    }

    private static string Count(int value, string singular, string plural) =>
        $"{value.ToString(CultureInfo.InvariantCulture)} {(value == 1 ? singular : plural)}";

    private static string Milliseconds(long microseconds) =>
        (microseconds / 1000.0).ToString("N0", CultureInfo.InvariantCulture) + " ms";

    private static void AppendTable(
        StringBuilder markdown, string heading, IReadOnlyList<string> columns, IEnumerable<IReadOnlyList<string>> rows)
    {
        markdown.AppendLine(heading);
        markdown.AppendLine();
        markdown.AppendLine("| " + string.Join(" | ", columns.Select(Cell)) + " |");
        markdown.AppendLine("| " + string.Join(" | ", columns.Select(_ => "---")) + " |");
        foreach (IReadOnlyList<string> row in rows)
        {
            markdown.AppendLine("| " + string.Join(" | ", row.Select(Cell)) + " |");
        }

        markdown.AppendLine();
    }

    /// <summary>
    /// One table cell. A prompt template, an adapter directory name and the hardware line
    /// are all free text a caller supplies, so a bare <c>|</c> would split a cell and a
    /// newline would inject a row.
    /// </summary>
    public static string Cell(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        return value
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace('\r', ' ')
            .Replace('\n', ' ')
            .Replace("|", "\\|", StringComparison.Ordinal);
    }

    /// <summary>
    /// Re-indent a served body for reading. Members and values are unchanged -- which is
    /// why the encoder is relaxed: the default one escapes an apostrophe, an em dash, a
    /// curly quote, a CJK character and an angle bracket to <c>\uXXXX</c>, so the same
    /// answer would read one way in its fenced quotation and another in the response
    /// printed to corroborate it.
    /// </summary>
    private static string Indent(string json)
    {
        using JsonDocument document = JsonDocument.Parse(json);
        return JsonSerializer.Serialize(
            document.RootElement,
            new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping });
    }
}
